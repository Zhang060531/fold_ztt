#include "main.h"
#include "string.h"
#include "LED_Task.h"
#include "cmsis_os.h"
#include "math.h"
#include "ws2812.h"

// 定义 PI
#ifndef PI
#define PI 3.14159265358979323846f
#endif

void LED_Task(void const * argument)
{
    static uint32_t counter = 0;
    uint8_t r, g, b;

    while (1)
    {
        // ==========================================
        // 1. 速度控制 (核心修改)
        // ==========================================
        // 0.0004f 是极慢速系数。
        // 在 1ms 的刷新率下，0.0004 rad/ms ≈ 0.4 rad/s
        // 这意味着颜色跑完一圈大约需要 15秒 (2π / 0.4)，非常优雅缓慢。
        float t = (float)counter * 0.0032f;

        // ==========================================
        // 2. 颜色计算 (基准速度 t)
        // ==========================================
        // 颜色按照 t 的速度缓慢流转
        float val_r = (sinf(t) + 1.0f) * 127.5f;
        float val_g = (sinf(t + 2.094f) + 1.0f) * 127.5f; // +120度
        float val_b = (sinf(t + 4.188f) + 1.0f) * 127.5f; // +240度

        // ==========================================
        // 3. 呼吸计算 (锁定为 3倍 速度)
        // ==========================================
        // 关键点：使用 t * 3.0f
        // 这样颜色每转一圈，亮度呼吸 3 次。
        // 保证了 红、绿、蓝 三个主色调出现时，亮度都正好处于波峰。
        float breath = (sinf(t * 3.0f) + 1.0f) * 0.5f;

        // 限制最低亮度，防止完全熄灭显得像断电 (范围 0.05 ~ 1.0)
        breath = breath * 0.95f + 0.05f;

        // ==========================================
        // 4. 融合输出
        // ==========================================
        r = (uint8_t)(val_r * breath);
        g = (uint8_t)(val_g * breath);
        b = (uint8_t)(val_b * breath);

        WS2812_Ctrl(r, g, b);

        counter++;
        osDelay(1); // 1000Hz 极致丝滑
    }
}