/* 【SPI 是干什么的】                                                               */
/*   SPI 是一种高速、全双工、主从式的串行通信总线，至少 4 根线：                       */
/*     SCK(时钟) / MOSI(主发从收) / MISO(主收从发) / CS(片选)                        */
/*   主机产生时钟，每个时钟周期主从各收发 1 bit，同时进行（全双工）。                  */
/*   本工程用 SPI2 与 BMI088 惯性传感器通信（读写它的寄存器）。                        */
/*                                                                                  */
/* 【关键函数】                                                                     */
/*   - BMI088_Read_Write_Byte() 发送 1 字节同时接收 1 字节（SPI 全双工特性）         */
/* ================================================================================ */

/* Define to prevent recursive inclusion -------------------------------------*/
#ifndef BSP_SPI_H
#define BSP_SPI_H


/* Include------------------------------------------------------------------*/
#include "stm32h7xx.h"

/* Externs ------------------------------------------------------------------*/
/**
 * @brief  SPI 收发 1 字节：发送 1 字节的同时接收 1 字节
 * @param  Tx_Data 要发送的数据
 * @retval 本次接收到的数据
 * @note   SPI 是全双工的，每发 1 bit 必然同时收 1 bit，所以读/写都通过这一个函数完成
 */
extern uint8_t BMI088_Read_Write_Byte(uint8_t Tx_Data);

#endif