/**
 ******************************************************************************
 * @file    ws2812.h
 * @brief   WS2812 可寻址 RGB 灯珠驱动头文件（SPI + DMA 模拟单总线时序）
 *
 * 【设备是什么】
 * WS2812 是常见的可寻址 RGB 灯珠，多颗可串联，用一根数据线逐位控制。
 * 每颗灯珠有 24bit 颜色数据（G、R、B 各 8bit），靠高低电平宽度区分 0/1。
 * 本工程用它做云台/底盘状态指示灯。
 *
 * 【通过什么接口连接】
 * 用 SPI 外设模拟单总线时序（WS2812_SPI_UNIT = hspi6）：
 * 把 SPI 的波特率设成合适的值后，用 1 个 SPI 字节去表示 WS2812 的 1bit，
 * 通过字节中高电平所占 bit 数来区分 0/1 码。原理详见 ws2812.c 顶部注释。
 *
 * 【被谁调用】
 *   - WS2812_Ctrl(r, g, b)：上层需要改变灯珠颜色时调用，设置红/绿/蓝亮度(0~255)。
 ******************************************************************************
 */
#ifndef __WS2812_H__
#define __WS2812_H__
 
 
#include "main.h" 


#define WS2812_SPI_UNIT     hspi6
extern SPI_HandleTypeDef WS2812_SPI_UNIT;
 
void WS2812_Ctrl(uint8_t r, uint8_t g, uint8_t b);
#endif
