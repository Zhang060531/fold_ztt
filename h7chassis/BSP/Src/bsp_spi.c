/* 文件说明：BSP 层 SPI（串行外设接口）驱动 —— 实现文件                              */
/* -------------------------------------------------------------------------------- */
/* 【作用】                                                                         */
/*   封装 HAL 的 SPI 收发函数，提供「发 1 字节收 1 字节」的原子操作，                 */
/*   供 BMI088 惯性传感器驱动调用，用来读写传感器的寄存器。                           */
/*                                                                                  */
/* 【SPI 全双工原理】                                                                */
/*   SPI 收发是同时进行的：主机每发出 1 个 bit，也会同步从从机收到 1 个 bit。          */
/*   所以读传感器寄存器时，也要先发一个「假数据」来换回从机返回的真实数据。            */
/*                                                                                  */
/* 【被谁调用】                                                                     */
/*   BMI088_Read_Write_Byte() 被 BMI088 驱动（bmi088.c）调用。                        */
/* ================================================================================ */

/* Includes ------------------------------------------------------------------*/
#include "bsp_spi.h"
#include "spi.h"

/**
  * @brief  SPI 收发 1 字节：发送 Tx_Data，同时接收 1 字节并返回
  * @param  Tx_Data 要发送的数据
  * @retval 本次接收到的数据（Rx_Data）
  * @note   HAL_SPI_TransmitReceive() 一次性完成「发 + 收」，长度 1，超时 100ms。
  *         因为 SPI 全双工，即使只想读，也必须发一个字节才能换回对方的数据。
  */
uint8_t BMI088_Read_Write_Byte(uint8_t Tx_Data)
{
	  uint8_t Rx_Data = 0;                              /* 接收缓冲区，初始 0 */

	  HAL_SPI_TransmitReceive(&hspi2,&Tx_Data,&Rx_Data,1,100); /* 发 1 字节并同步收 1 字节 */

    return Rx_Data;                                    /* 返回接收到的数据 */
}