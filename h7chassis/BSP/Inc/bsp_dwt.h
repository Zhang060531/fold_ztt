/* 【DWT 是干什么的】                                                               */
/*   DWT（Data Watchpoint and Trace）是 Cortex-M 内核自带的调试/观测单元。            */
/*   它内部有一个 32 位的 CYCCNT（Cycle Count，周期计数器）寄存器，                    */
/*   每个 CPU 时钟周期自动 +1，我们用它来精确测量微秒级时间、实现高精度延时。          */
/*   相比普通定时器，它不占额外外设、不依赖中断，读取开销极小。                        */
/*                                                                                  */
/* 【关键函数】                                                                     */
/*   - BSP_DWT_Init(CPU_Freq_mHz) 使能 DWT 周期计数器并记录 CPU 主频               */
/*                                                                                  */
/* 【被谁调用】                                                                     */
/*   - BSP_DWT_Init()：系统启动时（由 main 或 MCU_Init 相关流程）调用一次            */
/* ================================================================================ */

#ifndef BSP_DWT_H
#define BSP_DWT_H

/* Includes ------------------------------------------------------------------*/
#include "stdint.h"

/* Exported types ------------------------------------------------------------*/
/**
 * @brief DWT 时间结构体（秒/毫秒/微秒三段）
 * @note  用于把周期计数器换算成易读的时分形式，方便外部使用
 */
typedef struct
{
  uint32_t s;   /* 秒 */
  uint16_t ms;  /* 毫秒 */
  uint16_t us;  /* 微秒 */
} DWT_Time_Typedef;


/**
 * @brief  初始化 DWT 周期计数器，使能 CYCCNT 并记录 CPU 主频
 * @param  CPU_Freq_mHz  CPU 主频，单位 MHz（注意变量名写的是 mHz，实际传的是 MHz）
 * @retval 无
 * @note   必须在使用任何基于 DWT 的延时之前调用一次
 */
extern void BSP_DWT_Init(uint32_t CPU_Freq_mHz);

#endif